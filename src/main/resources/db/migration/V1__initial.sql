-- ==========================================
-- 1. Spring AI Chat Memory Schema
-- ==========================================
CREATE TABLE IF NOT EXISTS spring_ai_chat_memory (
    conversation_id TEXT NOT NULL,
    content TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('USER', 'ASSISTANT', 'SYSTEM', 'TOOL')),
    timestamp TEXT NOT NULL,
    sequence_id INTEGER PRIMARY KEY AUTOINCREMENT
) STRICT;

CREATE INDEX IF NOT EXISTS idx_spring_ai_chat_memory_conv_time
ON spring_ai_chat_memory(conversation_id, timestamp);

CREATE INDEX IF NOT EXISTS idx_spring_ai_chat_memory_conv_seq
ON spring_ai_chat_memory(conversation_id, sequence_id);


-- ==========================================
-- 2. Spring Session JDBC Schema (SQLite)
-- ==========================================
CREATE TABLE IF NOT EXISTS SPRING_SESSION (
    PRIMARY_ID TEXT NOT NULL,
    SESSION_ID TEXT NOT NULL,
    CREATION_TIME INTEGER NOT NULL,
    LAST_ACCESS_TIME INTEGER NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME INTEGER NOT NULL,
    PRINCIPAL_NAME TEXT,
    CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
) STRICT;

CREATE UNIQUE INDEX IF NOT EXISTS SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX IF NOT EXISTS SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX IF NOT EXISTS SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE IF NOT EXISTS SPRING_SESSION_ATTRIBUTES (
    SESSION_PRIMARY_ID TEXT NOT NULL,
    ATTRIBUTE_NAME TEXT NOT NULL,
    ATTRIBUTE_BYTES BLOB NOT NULL,
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
) STRICT;